export function setLanguage(newLang) {
	if (translations[newLang]) {
		lang.set(newLang);
		if (browser) {
			localStorage.setItem('eacphoto_lang', newLang);
			try { window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: newLang } })); } catch (e) {}
		}
	}
}
