// Load saved language
const savedLang = browser ? localStorage.getItem('eacphoto_lang') || 'zh' : 'zh';

export const lang = writable(translations[savedLang] ? savedLang : 'zh');

export const t = derived(lang, ($lang) => {
	return (key) => translations[$lang]?.[key] || key;
});

export function setLanguage(newLang) {
	if (translations[newLang]) {
		lang.set(newLang);
		if (browser) {
			localStorage.setItem('eacphoto_lang', newLang);
			// Dispatch event for external components (e.g., Turnstile)
			try {
				window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: newLang } }));
			} catch (e) {
				/* ignore */
			}
		}
	}
}

export { translations };
